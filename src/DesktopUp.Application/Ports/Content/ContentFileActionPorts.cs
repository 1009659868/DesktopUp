using DesktopUp.Domain;

namespace DesktopUp.Application;

public enum NewContentKind { Folder, TextFile, Shortcut }
public sealed record RegisteredManagedStorage(ManagedStorageRoot Root, Collection Collection);
public sealed record MappedNewContent(Guid CollectionId, string Path, string Identity);
public sealed record NewContentLocation(RegisteredManagedStorage? Storage, long ContentVersion, long PosterVersion)
{
    public MappedNewContent? Mapping { get; init; }
    public string Directory => Mapping?.Path ?? Storage!.Collection.StorageLocator!;
}

public interface IContentActionFiles
{
    string Normalize(string path);
    string Identity(string path);
    bool Exists(string path);
    bool Contains(string parent, string path);
    IDisposable LockDirectory(string path);
    IEnumerable<string> Enumerate(string directory);
    void RenameKnown(string source, string destination, string identity, string parentIdentity);
    byte[] EncodeShortcut(string target);
}

public sealed record PreparedContentCreation(Guid OperationId, string Source, string Destination);
public enum ContentCreationFinish { Completed, NotMoved, Preserved }
// The scope owns only files generated by this attempt. A durable/ambiguous receipt
// transfers cleanup ownership to the existing journal; Dispose must never delete it.
public interface IContentCreationAttempt : IDisposable
{
    PreparedContentCreation Prepare(string posterId, NewContentLocation location, NewContentKind kind,
        string name, byte[] bytes, CancellationToken token);
    ContentCreationFinish Complete(Guid operationId, CancellationToken token);
}
public interface IContentCreationStorage
{
    IContentCreationAttempt BeginAttempt(Action<string, string>? checkpoint);
}

public sealed record ContentDeletionResult(int Removed, bool Cancelled, IReadOnlyList<string> Errors);
public sealed record ShellDeleteResult(bool Cancelled, int HResult);
public interface IShellFileDeletion
{
    Task<ShellDeleteResult> Recycle(string path, nint owner, Func<bool> current, CancellationToken token);
}
public interface IContentDeletionAttempt
{
    IDisposable AcquireExecutor();
    IReadOnlyList<string> Prepare(string posterId, IReadOnlyList<string> itemIds);
    void AuthorizeDelete();
    bool IsCurrent(string path);
    int ObserveAndClose();
}
public interface IContentDeletionStorage
{
    IContentDeletionAttempt BeginAttempt();
}
public interface IContentFileActionContext
{
    DesktopStateSnapshot ReadState();
    MappedNewContent ResolveMappedLocation(string posterId);
    void ValidateMappedAction(string posterId, string? itemId);
    void RegisterShellCreated(string posterId, NewContentLocation location, string directoryIdentity, ShellCreatedItem created);
}
public interface IShellUiClient
{
    Task<ShellUiResult> RunAsync(ShellUiRequest request, CancellationToken stopping);
}

// Physical creation proof. The application decides when to verify, publish or clean.
public interface IOwnedContentCreationFiles
{
    IOwnedContentCreation Create(string path, NewContentKind kind, byte[] bytes);
}
public interface IOwnedContentCreation
{
    IDisposable PinUnchanged();
    void RemoveIfUnchanged();
}
